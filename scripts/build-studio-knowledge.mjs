// Updates the published copy used by Ask the Studio.
// Package prices come from the booking catalogue.
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');

const pageText = html => {
  const main = html.match(/<main[^>]*>([\s\S]*?)<\/main>/)?.[1] || html;
  return main
    .replace(/<(script|style|svg|select|template)[^>]*>[\s\S]*?<\/\1>/g, ' ')
    .replace(/<(h[1-4]|p|li|div|section|article|br|tr)[^>]*>/g, '\n')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&quot;/g, '"')
    .split('\n').map(line => line.replace(/\s+/g, ' ').trim()).filter(line => line.length > 1).join('\n');
};

const pages = [
  ['Homepage', 'index.html'],
  ['Online mixing and mastering', 'mixing-mastering.html'],
  ['Using an existing voucher', 'redeem.html'],
  ['Plug-ins', 'plugins.html'],
];
const sections = [];
for (const [title, file] of pages) {
  const html = await read(file);
  const copy = file === 'mixing-mastering.html'
    ? html.replace(/<strong data-mix-price="[^"]+">[^<]+<\/strong>/g, '')
    : html;
  sections.push(`## ${title}\n${pageText(copy)}`);
}

const knowledge = sections.join('\n\n');
await writeFile(new URL('api/lib/studio-knowledge.js', root),
  `// Generated by scripts/build-studio-knowledge.mjs from the public site copy.\nexport const studioKnowledge = ${JSON.stringify(knowledge)};\n`);
