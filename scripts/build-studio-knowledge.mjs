// Builds api/lib/studio-knowledge.js, the site copy the Ask the Studio assistant answers from.
// Run after changing page copy: node scripts/build-studio-knowledge.mjs
// Prices and availability are not copied here; the assistant reads those live from api/lib/catalog.js.
import { readFile, writeFile } from 'node:fs/promises';
import vm from 'node:vm';

const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');

const decode = text => text
  .replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"').replace(/&#39;|&rsquo;|&lsquo;/g, "'").replace(/&ldquo;|&rdquo;/g, '"')
  .replace(/&mdash;/g, '—').replace(/&ndash;/g, '–').replace(/&euro;/g, '€').replace(/&middot;/g, '·');
const pageText = html => {
  const main = html.match(/<main[^>]*>([\s\S]*?)<\/main>/)?.[1] || html;
  return decode(main
    .replace(/<(script|style|svg|select|template)[^>]*>[\s\S]*?<\/\1>/g, ' ')
    .replace(/<(h[1-4]|p|li|div|section|article|br|tr)[^>]*>/g, '\n')
    .replace(/<[^>]+>/g, ' '))
    .split('\n').map(line => line.replace(/\s+/g, ' ').trim()).filter(line => line.length > 1).join('\n');
};

// Service pages render their copy from servicePages in service-page.js; evaluate only that object.
const serviceSource = await read('service-page.js');
const servicePages = vm.runInNewContext(serviceSource.slice(0, serviceSource.indexOf('const pageKey')) + ';servicePages');
const flatten = value => Array.isArray(value) ? value.map(flatten).join(' — ') : typeof value === 'object' && value ? Object.values(value).map(flatten).join('\n') : String(value);
const services = Object.entries(servicePages).map(([key, page]) => `## Service page: ${key}\n${decode(flatten(page.en).replace(/<[^>]+>/g, ' '))}`);

const pages = [
  ['Homepage', 'index.html'], ['Gift vouchers', 'gift-vouchers.html'], ['The Hub Academy', 'hub-academy.html'],
  ['Music retreats', 'retreats.html'], ['Record label', 'record-label.html'], ['The Hub Culture', 'hub-culture.html'],
  ['Booking terms', 'terms.html'],
];
const sections = [];
for (const [title, file] of pages) sections.push(`## ${title} (${file})\n${pageText(await read(file))}`);

const knowledge = [...sections, ...services].join('\n\n').replace(/\n{3,}/g, '\n\n');
await writeFile(new URL('api/lib/studio-knowledge.js', root),
  `// Generated by scripts/build-studio-knowledge.mjs from the public site copy. Do not edit by hand.\nexport const studioKnowledge = ${JSON.stringify(knowledge)};\n`);
console.log(`studio-knowledge.js: ${knowledge.length} characters from ${pages.length} pages and ${services.length} service pages`);
